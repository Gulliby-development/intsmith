def test_parse_int_rejects_malformed_text(text: str, expected_message: str) -> None:
    assert_invalid("N", text, -BIG, BIG, expected_message)


@pytest.mark.parametrize(
    ("text", "lo", "hi", "expected_message"),
    [
        ("6", -5, 5, 'invalid N "6" (expected an integer from -5 to 5)'),
        ("-6", -5, 5, 'invalid N "-6" (expected an integer from -5 to 5)'),
        ("100", 0, 99, 'invalid N "100" (expected an integer from 0 to 99)'),
        ("10000", 0, 9999, 'invalid N "10000" (expected an integer from 0 to 9999)'),
        ("-10000", -9999, 0, 'invalid N "-10000" (expected an integer from -9999 to 0)'),
        (
            "99999999999999999999",
            0,
            9999,
            'invalid N "99999999999999999999" (expected an integer from 0 to 9999)',
        ),
    ],
)
def test_parse_int_rejects_values_outside_inclusive_bounds(
    text: str, lo: int, hi: int, expected_message: str
) -> None:
    assert_invalid("N", text, lo, hi, expected_message)


