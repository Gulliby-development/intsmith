def test_high_end_primality_and_neighbor_workload() -> None:
    # The engine has scalar primality/neighbor APIs; these literals exercise
    # the top of the 20-digit interval and the adjacent next-prime search.
    assert is_prime(99999999999999999989)
    assert not is_prime(99999999999999999999)
    assert next_prime(99999999999999999999) == 100000000000000000039
    assert prev_prime(100000000000000000040) == 100000000000000000039


def test_high_end_scalar_neighbor_workload() -> None:
    assert not is_prime(99999999999999989999)
    assert next_prime(99999999999999989999) == 99999999999999990167
    assert is_prime(99999999999999990167)


