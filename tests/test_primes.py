def test_high_end_prime_interval_workload(lower: int, upper: int, expected: list[int]) -> None:
    assert 0 <= upper - lower <= 10_000

    found: list[int] = []
    candidate = next_prime(lower - 1)
    while candidate <= upper:
        found.append(candidate)
        candidate = next_prime(candidate)

    assert found == expected


