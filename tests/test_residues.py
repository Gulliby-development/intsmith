import pytest

from intsmith.nt.residues import legendre, sqrt_mod_prime


@pytest.mark.parametrize(
    ("a", "p", "expected"),
    [
        (0, 13, 0),
        (13, 13, 0),
        (1, 13, 1),
        (10, 13, 1),
        (5, 13, -1),
        (2, 2, 0),
        (3, 2, 1),
        (1, 2, 1),
        (-3, 7, 1),
        (-2, 7, -1),
        (4, 7, 1),
        (9, 41, 1),
        (99999999999999999988, 99999999999999999989, 1),
        (1, 99999999999999999989, 1),
    ],
)
def test_legendre_symbols(a: int, p: int, expected: int) -> None:
    assert legendre(a, p) == expected


@pytest.mark.parametrize(
    ("a", "p", "expected"),
    [
        (0, 13, [0]),
        (13, 13, [0]),
        (10, 13, [6, 7]),
        (5, 13, []),
        (1, 13, [1, 12]),
        (2, 2, [0]),
        (3, 2, [1]),
        (1, 2, [1]),
        (9, 7, [3, 4]),
        (-3, 7, [2, 5]),
        (-2, 7, []),
        (9, 41, [3, 38]),
        (4, 99999999999999999989, [2, 99999999999999999987]),
        (9, 99999999999999999989, [3, 99999999999999999986]),
        (289, 99999999999999999989, [17, 99999999999999999972]),
        (
            15241578750190521,
            99999999999999999989,
            [123456789, 99999999999876543200],
        ),
        (1, 99999999999999999989, [1, 99999999999999999988]),
    ],
)
def test_square_roots_are_complete_sorted_and_distinct(a: int, p: int, expected: list[int]) -> None:
    assert sqrt_mod_prime(a, p) == expected
